package nl.tankarena.tools.mapconv

import java.io.File
import java.util.Base64

/**
 * Writes the original's two fonts and its palette into a Kotlin file for the client:
 *
 * - the 5×5 font of `src/graph/5x5font.s` (prompts, text pages, the status display): five rows
 *   per character, the leftmost pixel in bit 7, characters 0..127;
 * - `SETUP_FONT` of `DATA/SETSOUND.DAT`, the `big_font` of the menus: an Allegro 3 proportional
 *   font whose 224 glyphs (characters 32..255) are all 8×16, stored as 16 rows of 8 bits;
 * - `DATA/PALETTE.DAT`, the game palette, widened to 8 bits as the extracted pictures are.
 */
object LegacyFontExtractor {

    private const val SMALL_CHARACTERS = 128
    private const val BIG_FIRST = 32
    private const val BIG_CHARACTERS = 224
    private const val BIG_WIDTH = 8
    private const val BIG_HEIGHT = 16

    fun run(fontSource: File, dataDir: File, outputFile: File) {
        val small = readSmallFont(fontSource)
        val big = readBigFont(AllegroDatafile.read(File(dataDir, "SETSOUND.DAT")).getValue("SETUP_FONT"))
        val palette = File(dataDir, "PALETTE.DAT").readBytes().take(768).map { widen(it.toInt() and 0x3F).toByte() }.toByteArray()
        val encoder = Base64.getEncoder()
        outputFile.parentFile?.mkdirs()
        outputFile.writeText(
            """
            |// Generated by `mapconv extract-fonts` from src/graph/5x5font.s and DATA/; do not edit.
            |package nl.tankarena.ui.compose.legacy
            |
            |internal object GeneratedLegacyFonts {
            |    /** src/graph/5x5font.s: 5 rows per character, bit 7 leftmost, characters 0..127 (Base64). */
            |    const val FONT_5X5: String = "${encoder.encodeToString(small)}"
            |
            |    /** SETUP_FONT of DATA/SETSOUND.DAT: 16 rows of 8 bits per character, 32..255 (Base64). */
            |    const val BIG_FONT: String = "${encoder.encodeToString(big)}"
            |
            |    /** DATA/PALETTE.DAT: 256 × RGB, 8 bits per component (Base64). */
            |    const val PALETTE: String = "${encoder.encodeToString(palette)}"
            |}
            |""".trimMargin(),
        )
        println("Wrote fonts and palette -> ${outputFile.absolutePath}")
    }

    /** The assembler listing: `.fill n, 5, 0` for n blank characters, `.byte 0B…` for one row. */
    internal fun readSmallFont(source: File): ByteArray {
        val rows = ArrayList<Byte>()
        val fill = Regex("""^\s*\.fill\s+(\d+)\s*,\s*5\s*,\s*0""")
        val byte = Regex("""^\s*\.byte\s+0[Bb]([01]{8})""")
        for (line in source.readLines()) {
            fill.find(line)?.let { match -> repeat(match.groupValues[1].toInt() * 5) { rows += 0 } }
            byte.find(line)?.let { match -> rows += match.groupValues[1].toInt(2).toByte() }
        }
        require(rows.size % 5 == 0 && rows.size <= SMALL_CHARACTERS * 5) { "unexpected 5x5 font size ${rows.size}" }
        return ByteArray(SMALL_CHARACTERS * 5) { rows.getOrElse(it) { 0 } }
    }

    /** Allegro 3 `read_font()`: height −1, then per glyph a big-endian width, height and w×h bytes. */
    internal fun readBigFont(data: ByteArray): ByteArray {
        var position = 0
        fun word(): Int = ((data[position].toInt() shl 8) or (data[position + 1].toInt() and 0xFF)).also { position += 2 }
        require(word().toShort().toInt() == -1) { "SETUP_FONT is not a proportional font" }
        val out = ByteArray(BIG_CHARACTERS * BIG_HEIGHT)
        repeat(BIG_CHARACTERS) { glyph ->
            val width = word()
            val height = word()
            require(width == BIG_WIDTH && height == BIG_HEIGHT) { "glyph ${glyph + BIG_FIRST} is ${width}x$height" }
            for (y in 0 until height) {
                var bits = 0
                for (x in 0 until width) {
                    if (data[position + y * width + x].toInt() != 0) bits = bits or (0x80 ushr x)
                }
                out[glyph * BIG_HEIGHT + y] = bits.toByte()
            }
            position += width * height
        }
        return out
    }

    private fun widen(v: Int): Int = (v shl 2) or (v ushr 4)
}
