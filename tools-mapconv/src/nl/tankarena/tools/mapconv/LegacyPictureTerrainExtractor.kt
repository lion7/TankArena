package nl.tankarena.tools.mapconv

import java.io.File

/**
 * Extracts the gameplay columns of the legacy `pc{world}` arrays in `src/data/pictures.c`
 * (`pictureinfotype.speed` and `pictureinfotype.type`) into `GeneratedLegacyPictureTerrain`.
 *
 * Each row looks like `{{"NAME", ...}, {str0, str1, str2}, exptype, speed, linked, type}`.
 */
object LegacyPictureTerrainExtractor {
    private val worlds = listOf(
        "DESERT" to "pc0",
        "TEMPERATE" to "pc1",
        "CITY" to "pc2",
        "NIGHT" to "pc3",
    )

    fun generateKotlin(sourceFile: File, outputFile: File) {
        val source = sourceFile.readText()
        val catalogs = worlds.associate { (label, variable) -> label to parseRows(source, variable) }
        outputFile.parentFile?.mkdirs()
        outputFile.writeText(renderKotlin(catalogs))
    }

    internal data class Row(
        val type: String,
        val speed: Float,
        val strength: List<Int>,
        val explosion: String,
        val links: String,
    )

    internal fun parseRows(source: String, variable: String): List<Row> {
        val marker = "$variable[]={"
        val start = source.indexOf(marker)
        require(start >= 0) { "Could not find $variable in pictures.c source." }
        val blockStart = start + marker.length
        val blockEnd = source.indexOf("};", blockStart)
        require(blockEnd > blockStart) { "Could not find end of $variable initializer." }
        val block = source.substring(blockStart, blockEnd)

        val rows = mutableListOf<Row>()
        var depth = 0
        val current = StringBuilder()
        for (character in block) {
            if (character == '{') depth += 1
            if (depth > 0) current.append(character)
            if (character == '}') {
                depth -= 1
                if (depth == 0) {
                    // The arrays end with a `{{""}}` sentinel row.
                    if (current.contains("{{\"\"}}")) break
                    rows += parseRow(current.toString())
                    current.clear()
                }
            }
        }
        return rows
    }

    /** `{{names}, {strengths}, exptype, speed, linked, type}`. */
    private fun parseRow(row: String): Row {
        val inner = row.trim().removePrefix("{").removeSuffix("}")
        val afterNames = inner.indexOf('}') + 1
        val strengthsStart = inner.indexOf('{', afterNames)
        val afterStrengths = inner.indexOf('}', strengthsStart) + 1
        val strength = inner.substring(strengthsStart + 1, afterStrengths - 1).split(',')
            .mapNotNull { it.trim().toIntOrNull() }
        val scalars = inner.substring(afterStrengths).split(',').map { it.trim() }.filter { it.isNotEmpty() }
        require(scalars.size == 4) { "Unexpected picture row: $row" }
        return Row(
            type = scalars[3],
            speed = scalars[1].toFloat(),
            strength = (strength + listOf(0, 0, 0)).take(3),
            explosion = scalars[0],
            links = scalars[2],
        )
    }

    private fun renderKotlin(catalogs: Map<String, List<Row>>): String {
        val builder = StringBuilder()
        builder.appendLine("package nl.tankarena.content")
        builder.appendLine()
        builder.appendLine("// Generated by :tools-mapconv extract-picture-terrain from src/data/pictures.c")
        builder.appendLine("// (pictureinfotype type, speed, str, exptype and linked per picture index). Do not edit by hand.")
        builder.appendLine("internal object GeneratedLegacyPictureTerrain {")
        catalogs.forEach { (label, rows) ->
            builder.appendLine("    val ${label.lowercase()}: List<LegacyPictureTerrain> by lazy { build$label() }")
            builder.appendLine()
        }
        catalogs.forEach { (label, rows) ->
            builder.appendLine("    private fun build$label(): List<LegacyPictureTerrain> = listOf(")
            rows.forEach { row ->
                val strength = row.strength.joinToString(", ")
                builder.appendLine(
                    "        LegacyPictureTerrain(\"${row.type}\", ${row.speed}f, listOf($strength), \"${row.explosion}\", \"${row.links}\"),",
                )
            }
            builder.appendLine("    )")
            builder.appendLine()
        }
        builder.appendLine("}")
        return builder.toString()
    }
}
