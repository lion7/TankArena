package nl.tankarena.tools.mapconv

import java.io.File

/**
 * Extracts the `tank[num_tanks]` table from src/data/tanks.c into `GeneratedLegacyVehicles`, so the
 * server can use the legacy per-vehicle motion, armor and weapon numbers (`tankinfotype` in
 * src/include/types.h) without hand-copying them.
 */
object LegacyVehicleExtractor {

    fun generateKotlin(sourceFile: File, outputFile: File) {
        val vehicles = parse(sourceFile.readText())
        outputFile.parentFile?.mkdirs()
        outputFile.writeText(render(vehicles))
    }

    /** A brace-initializer tree: leaves are tokens, branches are `{ ... }` groups. */
    private sealed interface Node {
        data class Leaf(val token: String) : Node
        data class Group(val items: List<Node>) : Node
    }

    internal fun parse(source: String): List<List<String>> {
        val start = source.indexOf("tank[num_tanks]={")
        require(start >= 0) { "Could not find the tank[] initializer in tanks.c." }
        val tokens = tokenize(source.substring(source.indexOf('{', start)))
        val root = readGroup(tokens, Cursor())
        return root.items.map { vehicle -> flatten(vehicle) }
    }

    private class Cursor(var index: Int = 0)

    private fun tokenize(text: String): List<String> {
        val tokens = mutableListOf<String>()
        var i = 0
        while (i < text.length) {
            val c = text[i]
            when {
                c.isWhitespace() || c == ',' -> i++
                c == '/' && text.startsWith("/*", i) -> i = text.indexOf("*/", i) + 2
                c == '{' || c == '}' -> {
                    tokens += c.toString()
                    i++
                    // Stop after the initializer's closing brace.
                    if (c == '}' && tokens.count { it == "{" } == tokens.count { it == "}" }) return tokens
                }
                c == '"' -> {
                    val end = text.indexOf('"', i + 1)
                    tokens += text.substring(i, end + 1)
                    i = end + 1
                }
                else -> {
                    val end = (i until text.length).firstOrNull { text[it].isWhitespace() || text[it] in ",{}" } ?: text.length
                    tokens += text.substring(i, end)
                    i = end
                }
            }
        }
        return tokens
    }

    private fun readGroup(tokens: List<String>, cursor: Cursor): Node.Group {
        require(tokens[cursor.index] == "{")
        cursor.index++
        val items = mutableListOf<Node>()
        while (tokens[cursor.index] != "}") {
            items += if (tokens[cursor.index] == "{") readGroup(tokens, cursor) else Node.Leaf(tokens[cursor.index++])
        }
        cursor.index++
        return Node.Group(items)
    }

    /** One vehicle as its top-level fields, each flattened to its leaves (missing trailing values stay absent). */
    private fun flatten(vehicle: Node): List<String> = (vehicle as Node.Group).items.map { field ->
        leaves(field).joinToString(" ")
    }

    private fun leaves(node: Node): List<String> = when (node) {
        is Node.Leaf -> listOf(node.token)
        is Node.Group -> node.items.flatMap(::leaves)
    }

    private fun render(vehicles: List<List<String>>): String = buildString {
        appendLine("package nl.tankarena.sim")
        appendLine()
        appendLine("// Generated by :tools-mapconv extract-vehicles from src/data/tanks.c. Do not edit by hand.")
        appendLine("internal object GeneratedLegacyVehicles {")
        appendLine("    val vehicles: List<VehicleSpec> by lazy { build() }")
        appendLine()
        appendLine("    private fun build(): List<VehicleSpec> = listOf(")
        vehicles.forEachIndexed { index, fields -> append(renderVehicle(index, fields)) }
        appendLine("    )")
        appendLine("}")
    }

    private fun renderVehicle(index: Int, fields: List<String>): String {
        fun numbers(field: Int): List<String> = fields.getOrNull(field)?.split(' ')?.filter { it.isNotBlank() } ?: emptyList()
        val type = fields[0]
        val motion = numbers(1)
        val turret = numbers(2)
        val props = numbers(3)
        val general = numbers(4).let { listOf(it[0], it[1], it.drop(2).joinToString(" ")) }
        val weap = numbers(5)
        val waveDelay = numbers(6).firstOrNull() ?: "0"
        fun floats(values: List<String>) = values.joinToString(", ") { "${it.toFloat()}f" }
        // `{count, x1, y1, x2, y2, ...}` for the gun lists, plain `{x1, y1, ...}` for smoke and rocket.
        fun points(values: List<String>, counted: Boolean): String {
            val coordinates = if (counted) values.drop(1).take(values.first().toInt() * 2) else values
            return coordinates.chunked(2).filter { it.size == 2 }.joinToString(", ", "listOf(", ")") { (x, y) -> "$x to $y" }
        }
        val mainGuns = points(numbers(7), counted = true)
        val chainGuns = points(numbers(8), counted = true)
        val smokes = points(numbers(9), counted = false)
        val rocket = numbers(10).let { if (it.size >= 2) "${it[0]} to ${it[1]}" else "0 to 0" }
        // `{count, LI_SIZE, x, y, ...}`: the headlights used on night maps (light_tank()).
        val lights = numbers(11).let { values ->
            val count = values.firstOrNull()?.toIntOrNull() ?: 0
            values.drop(1).chunked(3).take(count).filter { it.size == 3 }.joinToString(", ", "listOf(", ")") { (size, x, y) ->
                val index = when (size) { "LI_LARGE" -> 0; "LI_MEDIUM" -> 1; "LI_SMALL" -> 2; else -> size.toInt() }
                "VehicleLight($index, $x to $y)"
            }
        }
        fun ints(values: List<String>) = values.joinToString(", ") { it.toBoolean01() }
        return buildString {
            appendLine("        // $index ${general[2]}")
            appendLine("        VehicleSpec(")
            appendLine("            name = ${general[2]},")
            appendLine("            kind = VehicleKind.$type,")
            appendLine("            motion = VehicleMotion(${floats(motion.take(8))}, rotation = ${motion[8]}, change = ${motion[9]}),")
            appendLine("            turretOffset = ${turret[0]} to ${turret[1]},")
            appendLine("            turretMode = TurretMode.${turret[2].removePrefix("MAIN_")},")
            appendLine("            autoRotation = ${turret[3]},")
            appendLine("            height = ${props[0]},")
            appendLine("            radius = ${props[1]},")
            appendLine("            armor = ${props[2]},")
            appendLine("            maxFuel = ${props[3]},")
            appendLine("            crashDamage = ${general[0]},")
            appendLine("            smokes = ${general[1].toBooleanLiteral()},")
            appendLine("            mainGunHitType = \"${weap[0]}\",")
            appendLine("            hasFlamer = ${weap[1].toBooleanLiteral()},")
            appendLine("            initialWeapon = ${weap[2]},")
            appendLine("            ammo = listOf(${ints(weap.subList(3, 15))}),")
            appendLine("            refireTicks = listOf(${ints(weap.subList(15, 27))}),")
            appendLine("            power = listOf(${ints(weap.subList(27, 39))}),")
            appendLine("            waveDelay = $waveDelay,")
            appendLine("            mainGuns = $mainGuns,")
            appendLine("            chainGuns = $chainGuns,")
            appendLine("            smokePoints = $smokes,")
            appendLine("            rocketOffset = $rocket,")
            appendLine("            lights = $lights,")
            appendLine("        ),")
        }
    }

    private fun String.toBooleanLiteral(): String = when (this) {
        "TRUE" -> "true"
        "FALSE" -> "false"
        else -> (this.toInt() != 0).toString()
    }

    private fun String.toBoolean01(): String = when (this) {
        "TRUE" -> "1"
        "FALSE" -> "0"
        else -> this
    }
}
